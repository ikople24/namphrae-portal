/**
 * แผนที่ค่า → สี ของเลเยอร์หนึ่ง
 *
 * ไล่สีตามลำดับค่าที่เรียงแล้ว ไม่ใช่ตาม hash ของค่า — hash ชนกันได้ง่ายเมื่อมี
 * ค่าไม่กี่ค่า แล้วสองหมู่ที่ติดกันจะได้สีเดียวกันจนดูเหมือนเป็นผืนเดียว ส่วนการ
 * เรียงก่อนรับประกันว่าค่าไม่เกินขนาดจานสีจะได้สีคนละสีเสมอ และได้สีเดิมทุกครั้ง
 * ที่โหลดใหม่ (ตราบใดที่ชุดค่าไม่เปลี่ยน)
 */
export function buildColorGroups(values: string[]): Map<string, string> {
  const sorted = [...new Set(values)].sort((a, b) =>
    a.localeCompare(b, 'th', { numeric: true })
  );
  const out = new Map<string, string>();
  sorted.forEach((v, i) => out.set(v, GROUP_PALETTE[i % GROUP_PALETTE.length]));
  return out;
}

