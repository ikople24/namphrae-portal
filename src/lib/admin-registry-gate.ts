/**
 * ตัดสินว่าจะให้เข้าหลังบ้านได้ไหมเมื่อ "ไม่มีทะเบียนผู้ใช้ให้ตรวจ"
 * (ตั้ง Clerk ไว้แล้ว แต่ไม่ได้ตั้ง MONGODB_URI)
 *
 * แยกออกมาเป็นฟังก์ชันบริสุทธิ์เพราะ auth-server.ts ลาก Clerk กับ mongodb เข้ามา
 * ทำให้เทสต์ตรง ๆ ไม่ได้ — และกฎข้อนี้เป็นกฎความปลอดภัย ควรมีเทสต์ตรึงไว้
 *
 * dev: ปล่อยผ่าน — โปรเจกต์นี้ตั้งใจให้รันได้โดยไม่ต้องตั้งค่าอะไรเลย
 *      (`npm run dev` ใช้ไฟล์ JSON แทน Mongo และเปิดหลังบ้านให้ทดสอบ)
 * production: ปฏิเสธ — ไม่มี deployment จริงไหนที่ไม่ต้องมี MONGODB_URI
 *      การลืมตัวแปรเดียวไม่ควรเปลี่ยนหลังบ้านเป็นเปิดรับทุกคนที่ล็อกอินได้
 */
export function allowAdminWithoutRegistry(nodeEnv: string | undefined): boolean {
  return nodeEnv !== 'production';
}
