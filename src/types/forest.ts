// src/types/forest.ts
import type { MapLayer } from '@/types/map';

// ป่าไม้เป็นโดเมนแยก — คนละ collection คนละ URL คนละสิทธิ์ — แต่รูปร่างของชั้นข้อมูล
// เหมือนแผนที่ทุกประการ เพราะเดินผ่าน pipeline เดียวกัน ต่างกันแค่สองฟิลด์ที่มีความหมาย
// เฉพาะหน้าป่าไม้เท่านั้น
export type ForestLayer = MapLayer & {
  /**
   * ยังไม่มีโค้ดอ่านค่านี้ — และรอบ 2 ตั้งใจไม่เดินสายให้
   *
   * ค่าที่ใช้จริงตอนนี้อยู่ที่ `LAYER_STYLES[layerId].defaultOn` ใน `map-style.ts`
   * ซึ่งครอบทั้งเจ็ดชั้นที่นำเข้ามาแล้ว: ชั้นหนัก (ป่าสงวน 3.6 MB, ป่าถาวร 2.4 MB,
   * แหล่งน้ำ 327 เส้น) ปิดไว้ เพราะคนเปิดหน้าป่าไม้ของน้ำแพร่มาดูป่าของน้ำแพร่
   * ไม่ได้มาดูป่าสงวนทั้งสามจังหวัด
   *
   * ฟิลด์นี้จะมีความหมายในรอบ 3 ที่เจ้าหน้าที่สร้างชั้นเองได้ — ชั้นที่สร้างใหม่ไม่มี
   * รายการใน `LAYER_STYLES` จึงต้องบอกค่านี้จากหลังบ้าน และจะมีหน้าตั้งค่าให้กรอก
   * พร้อมกัน การเดินสายก่อนถึงตอนนั้นจะได้ท่อที่ไม่มีอะไรไหลผ่าน
   */
  defaultOn?: boolean;
  /**
   * ยังไม่มีโค้ดอ่านค่านี้ — เมื่อรอบ 4 มาถึงจะเป็นสวิตช์ที่เปิดให้เติม photo_url ลงไฟล์
   * สาธารณะตอนเผยแพร่ ค่าเริ่มต้นปิด หลักเดียวกับ publicFields เพราะรูปถ่ายภาคสนาม
   * อาจติดคนหรือติดบ้านคนมาโดยไม่มีใครตั้งใจ
   */
  publishPhotos?: boolean;
};
